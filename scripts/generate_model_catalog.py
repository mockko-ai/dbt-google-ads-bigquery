#!/usr/bin/env python3
"""Generate docs/model_catalog.md from the data dictionary workbook, and check coverage.

    python scripts/generate_model_catalog.py

* Every table whose Disposition is Build or Stage only must have a staging model file.
* Every model named in the workbook's Feeds column must exist under models/marts/core.
The script exits non-zero if either check fails. Requires: openpyxl.
"""
import collections
import os
import re
import sys

import openpyxl

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scaffold_staging import families_for  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKBOOK = os.path.join(ROOT, "spec", "google_ads_data_dictionary.xlsx")
OUT = os.path.join(ROOT, "docs", "model_catalog.md")


def models_in(path):
    return sorted(f[:-4] for f in os.listdir(os.path.join(ROOT, path)) if f.endswith(".sql"))


def main():
    wb = openpyxl.load_workbook(WORKBOOK, read_only=True)
    t = list(wb["Tables"].iter_rows(values_only=True))
    tables = [dict(zip(t[0], r)) for r in t[1:]]

    staging_files = set(models_in("models/staging"))
    core_files = set(models_in("models/marts/core"))
    problems = []

    built = [r for r in tables if r["Disposition"] in ("Build", "Stage only")]
    for r in built:
        if r["Staging model"] not in staging_files:
            problems.append(f"missing staging model {r['Staging model']} for {r['Table']}")
    extra = staging_files - {r["Staging model"] for r in built}
    for e in sorted(extra):
        problems.append(f"staging model {e} has no Build/Stage only row in the workbook")

    feeds = collections.defaultdict(list)  # target model -> source tables
    for r in built:
        if r["Feeds"]:
            target = re.sub(r"\s*\(.*\)$", "", r["Feeds"]).strip()
            feeds[target].append(r["Table"])
    for target in feeds:
        if target not in core_files:
            problems.append(f"workbook feeds {target} but models/marts/core/{target}.sql does not exist")

    counts = collections.Counter(r["Disposition"] for r in tables)
    dims = sorted(m for m in core_files if m.startswith(("dim_", "bridge_")))
    facts = sorted(m for m in core_files if m.startswith("fct_"))
    inter = models_in("models/intermediate")
    reporting = models_in("models/marts/reporting")

    L = []
    L.append("# Model catalog\n")
    L.append("Generated by `scripts/generate_model_catalog.py` from `spec/google_ads_data_dictionary.xlsx`. Do not edit by hand.\n")
    L.append(f"- Source tables in the workbook: {len(tables)} (Build {counts['Build']}, Stage only {counts['Stage only']}, Skip {counts['Skip']})")
    L.append(f"- Staging models: {len(staging_files)}")
    L.append(f"- Intermediate models: {len(inter)}")
    L.append(f"- Dims and bridges: {len(dims)}")
    L.append(f"- Facts: {len(facts)}")
    L.append(f"- Reporting models: {len(reporting)}\n")

    L.append("## Staging models\n")
    L.append("| Model | Source table | Kind | Level | Grain (keys + segments) | Disposition | Feeds | Feature flag(s) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in sorted(built, key=lambda r: r["Staging model"]):
        flags = ", ".join(f"`google_ads__using_{f}`" for f in families_for(r["Table"][4:]))
        L.append(f"| `{r['Staging model']}` | `{r['Table']}` | {r['Kind']} | {r['Level']} | {r['Grain (keys + segments)'] or ''} | {r['Disposition']} | {r['Feeds'] or ''} | {flags} |")

    L.append("\n## Dimensions and bridges\n")
    L.append("| Model | Built from |")
    L.append("|---|---|")
    for m in dims:
        src = ", ".join(f"`{s}`" for s in feeds.get(m, [])) or "derived (see model description)"
        L.append(f"| `{m}` | {src} |")

    L.append("\n## Facts\n")
    L.append("| Model | Built from |")
    L.append("|---|---|")
    for m in facts:
        src = ", ".join(f"`{s}`" for s in feeds.get(m, [])) or ""
        L.append(f"| `{m}` | {src} |")

    L.append("\n## Intermediate models\n")
    L.extend(f"- `{m}`" for m in inter)
    L.append("\n## Reporting models\n")
    L.extend(f"- `{m}`" for m in reporting)

    L.append("\n## Skipped source tables\n")
    L.append("| Table | Kind | Reason |")
    L.append("|---|---|---|")
    for r in tables:
        if r["Disposition"] == "Skip":
            L.append(f"| `{r['Table']}` | {r['Stats type'] or r['Kind']} | {r['Notes'] or ''} |")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"staging {len(staging_files)}, intermediate {len(inter)}, dims+bridges {len(dims)}, facts {len(facts)}, reporting {len(reporting)}")
    if problems:
        print("\n".join("PROBLEM: " + p for p in problems))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
