{# stg_google_ads__bid_goal: generated by scripts/scaffold_staging.py from ads_BidGoal, then reviewed by hand. #}

with source as (

    select * from {{ google_ads_source('BidGoal') }}
    where _DATA_DATE = _LATEST_DATE

),

renamed as (

    select
        bidding_strategy_id,
        customer_id,
        bidding_strategy_name,
        bidding_strategy_status,
        cast(bidding_strategy_target_cpa_cpc_bid_ceiling_micros as numeric) / 1000000 as bidding_strategy_target_cpa_cpc_bid_ceiling,
        cast(bidding_strategy_target_cpa_cpc_bid_floor_micros as numeric) / 1000000 as bidding_strategy_target_cpa_cpc_bid_floor,
        cast(bidding_strategy_target_cpa_target_cpa_micros as numeric) / 1000000 as bidding_strategy_target_cpa_target_cpa,
        cast(bidding_strategy_target_roas_cpc_bid_ceiling_micros as numeric) / 1000000 as bidding_strategy_target_roas_cpc_bid_ceiling,
        cast(bidding_strategy_target_roas_cpc_bid_floor_micros as numeric) / 1000000 as bidding_strategy_target_roas_cpc_bid_floor,
        bidding_strategy_target_roas_target_roas,
        cast(bidding_strategy_target_spend_cpc_bid_ceiling_micros as numeric) / 1000000 as bidding_strategy_target_spend_cpc_bid_ceiling,
        cast(bidding_strategy_target_spend_target_spend_micros as numeric) / 1000000 as bidding_strategy_target_spend_target_spend,
        bidding_strategy_type,
        customer_descriptive_name
    from source

)

select * from renamed
