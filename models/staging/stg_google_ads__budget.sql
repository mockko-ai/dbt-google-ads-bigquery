    select * from {{ google_ads_source('Budget') }}
    where _DATA_DATE = _LATEST_DATE

),

renamed as (

    select
        campaign_budget_id,
        customer_id,
        cast(campaign_budget_amount_micros as numeric) / 1000000 as campaign_budget_amount,
        campaign_budget_delivery_method,
        campaign_budget_explicitly_shared,
        campaign_budget_has_recommended_budget,
        campaign_budget_name,
        campaign_budget_period,
        cast(campaign_budget_recommended_budget_amount_micros as numeric) / 1000000 as campaign_budget_recommended_budget_amount,
        campaign_budget_reference_count,
        campaign_budget_status,
        cast(campaign_budget_total_amount_micros as numeric) / 1000000 as campaign_budget_total_amount,
        customer_descriptive_name
    from source

)

select * from renamed
